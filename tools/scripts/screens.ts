// Writes tests/support/screens.ts from the Cockpit spec's section 12 (docs/design/cockpit.md): each screen's
// text blocks, as the rows the screen tests compare with. The plugin's test harness reads no files, so the rows are
// kept as source. `--check` fails when the file is not what the spec gives (run in `bun run --cwd tools check`).
// Run from the repository root: `bun tools/scripts/screens.ts` (or `--check`).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const md = readFileSync(join(root, 'docs/design/cockpit.md'), 'utf8')
const target = join(root, 'tests/support/screens.ts')
const parts = md.split(/^#### 12\.(\d+) /m)
const blocks: Record<string, string[][]> = {}

for (let i = 1; i < parts.length; i += 2) {
  blocks[(parts[i] ?? '').padStart(2, '0')] = Array.from((parts[i + 1] ?? '').matchAll(/```text\n([\s\S]*?)```/g), m =>
    (m[1] ?? '').replace(/\n$/, '').split('\n')
  )
}

const text = `// Generated by tools/scripts/screens.ts from docs/design/cockpit.md section 12: do not edit by hand.
// The screens' text blocks (the left, then the pane; or the one screen), the rows the screen tests compare with.
import type { Part } from '../../hooks/shared/parts'

const SCREENS: Record<string, string[][]> = ${JSON.stringify(blocks, null, 2)}

/**
 * A screen's text block.
 * @param n the screen, \`01\` to \`33\`
 * @param block 0 for the left (or the one screen), 1 for the pane
 * @returns its rows
 */
export function screen(n: string, block = 0): string[] {
  const rows = SCREENS[n]?.[block]

  if (rows === undefined) throw new Error(\`no screen \${n} block \${block} in the spec\`)

  return rows
}

/** Rows as a screen shows them: each row's text, trailing blanks dropped (the spec drops them too). */
export const shown = (rows: readonly (readonly Part[])[]): string[] => rows.map(r => r.map(p => p.t).join('').trimEnd())
`

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    console.error('tests/support/screens.ts is not the spec`s section 12: run `bun tools/scripts/screens.ts`')
    process.exit(1)
  }

  console.log('screens: ok')
} else {
  writeFileSync(target, text)
  console.log(`screens: wrote ${Object.keys(blocks).length} screens`)
}
